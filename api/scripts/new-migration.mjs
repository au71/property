#!/usr/bin/env node
/**
 * Creates and applies a new Prisma migration.
 *
 * Why this exists instead of `prisma migrate dev`:
 *
 * Full-text search uses `listing_fts`, a SQLite FTS5 virtual table with its
 * shadow tables and sync triggers, created by a hand-written migration. Virtual
 * tables cannot be expressed in schema.prisma, so `migrate dev` — which diffs
 * the schema against the *live database* — sees them as orphans and offers to
 * drop the search index. Worse, that warning makes it prompt, so it cannot run
 * unattended at all.
 *
 * `migrate diff --from-migrations --to-schema` compares the migration
 * history with the schema and never looks at the live database, so the FTS
 * objects are outside its view entirely. It is also non-interactive, which makes
 * this scriptable and safe in CI.
 *
 *   npm run db:migrate:new -- --name add_something
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const MIGRATIONS_DIR = 'prisma/migrations';
const FTS_OBJECT = /listing_fts/i;

const args = process.argv.slice(2);
const nameIndex = args.indexOf('--name');
if (nameIndex === -1 || !args[nameIndex + 1]) {
  console.error('Usage: npm run db:migrate:new -- --name <migration_name>');
  process.exit(1);
}
const name = args[nameIndex + 1];
if (!/^[a-z0-9_]+$/.test(name)) {
  console.error('Migration names should be lower_snake_case.');
  process.exit(1);
}

const run = (cmd, cmdArgs, opts = {}) =>
  execFileSync(cmd, cmdArgs, {
    stdio: 'inherit',
    shell: process.platform === 'win32',
    ...opts,
  });

const capture = (cmd, cmdArgs) =>
  execFileSync(cmd, cmdArgs, { encoding: 'utf8', shell: process.platform === 'win32' });

const raw = capture('npx', [
  'prisma',
  'migrate',
  'diff',
  '--from-migrations',
  MIGRATIONS_DIR,
  '--to-schema',
  'prisma/schema',
  '--script',
]);

/**
 * Split into statements, keeping each one's leading `-- Comment` header with it
 * so a stripped block does not leave an orphaned comment behind.
 */
const blocks = raw
  .split(/\n(?=-- )/)
  .map((block) => block.trim())
  .filter((block) => block.length > 0 && !/^Loaded Prisma config/.test(block));

const kept = blocks.filter((block) => !FTS_OBJECT.test(block));
const stripped = blocks.length - kept.length;

const hasStatements = kept.some((block) =>
  block.split('\n').some((line) => line.trim() && !line.trim().startsWith('--')),
);

if (!hasStatements) {
  console.log('No schema changes detected; nothing to migrate.');
  process.exit(0);
}

const header = [
  `-- Generated by scripts/new-migration.mjs from \`prisma migrate diff\`.`,
  stripped > 0
    ? `-- ${stripped} statement block(s) targeting the listing_fts search index were\n-- removed: Prisma cannot see virtual tables and always proposes dropping them.`
    : null,
  '',
]
  .filter((line) => line !== null)
  .join('\n');

const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const dir = join(MIGRATIONS_DIR, `${stamp}_${name}`);
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'migration.sql'), `${header}\n${kept.join('\n\n')}\n`);

console.log(`\nWrote ${dir}/migration.sql:\n`);
console.log(readFileSync(join(dir, 'migration.sql'), 'utf8'));
if (stripped > 0) console.log(`(stripped ${stripped} FTS block(s))\n`);

run('npx', ['prisma', 'migrate', 'deploy']);
run('npx', ['prisma', 'generate']);
console.log('\nMigration created and applied.');
